// npm run content:build
// Builds every content chunk into public/data plus the manifest and licence docs.
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { fetchAptitude } from './aptitude.mjs'
import { fetchCards } from './cards.mjs'
import { hash } from './lib.mjs'
import { fetchTopics } from './topics.mjs'
import { fetchWikidataQuizzes } from './wikidata.mjs'

const CHUNK = 400
const OUT = 'public/data'
const ENRICHED = 'pipeline/.cache/enriched.json'

async function main() {
  console.log('1. Topics (Wikipedia Vital Articles, Level 5)')
  const topics = await fetchTopics()
  writeFileSync('pipeline/.cache/topics.json', JSON.stringify(topics))
  console.log(`   ${topics.length} topics`)

  console.log('2. Card text (Wikipedia REST summaries)')
  let cards = await fetchCards(topics)
  if (existsSync(ENRICHED)) {
    // Optional enrichment from pipeline/enrich.mjs, merged only when its quotes checked out.
    const extra = JSON.parse(readFileSync(ENRICHED, 'utf8'))
    cards = cards.map((c) => (extra[c.id] && extra[c.id].title === c.title ? { ...c, ...extra[c.id].fields, modified: true, reviewed: false } : c))
  }
  console.log(`   ${cards.length} cards`)

  console.log('3. Quiz items (Wikidata SPARQL)')
  const quizzes = await fetchWikidataQuizzes()
  console.log(`   ${quizzes.length} quiz items`)

  console.log('4. Aptitude (GSM8K)')
  const apt = await fetchAptitude()

  console.log('5. Output')
  rmSync(OUT, { recursive: true, force: true })
  mkdirSync(OUT, { recursive: true })
  const chunks = []
  const groups = new Map()
  for (const it of [...cards, ...quizzes, ...apt]) {
    const key = it.type + '|' + it.category
    groups.set(key, [...(groups.get(key) ?? []), it])
  }
  for (const [key, list] of groups) {
    const [type, category] = key.split('|')
    for (let n = 0; n * CHUNK < list.length; n++) {
      const part = list.slice(n * CHUNK, (n + 1) * CHUNK)
      const file = `${type}-${category}-${n}.json`
      const json = JSON.stringify(part)
      writeFileSync(`${OUT}/${file}`, json)
      chunks.push({ file, type, category, n, count: part.length, hash: hash(json) })
    }
  }
  const counts = {
    cards: cards.length,
    quiz: quizzes.length,
    aptitude: apt.length,
    riddles: JSON.parse(readFileSync('content/riddles/riddles.json', 'utf8')).length,
  }
  const manifest = { version: hash(chunks.map((c) => c.hash).join()), generated: new Date().toISOString(), chunkSize: CHUNK, chunks, counts }
  writeFileSync(`${OUT}/manifest.json`, JSON.stringify(manifest, null, 1))
  const bytes = readdirSync(OUT).reduce((s, f) => s + readFileSync(`${OUT}/${f}`).length, 0)
  console.log(`   ${chunks.length} chunks, ${(bytes / 1e6).toFixed(1)} MB raw`, counts)
  writeLicenses(counts)
}

function writeLicenses(counts) {
  writeFileSync(
    'docs/CONTENT_LICENSES.md',
    `# Content licences

Generated by \`npm run content:build\` on ${new Date().toISOString().slice(0, 10)}. Every item in \`public/data\` carries its own \`license\`, \`source\` and \`attribution\` fields.

| Content | Count | Source | Licence | How it is used |
|---|---|---|---|---|
| Star Chart cards | ${counts.cards} | Wikipedia page summaries for Vital Articles (Level 5): astronomy, physics, chemistry, earth science, meteorology, geography, biology, mathematics | CC BY-SA 4.0 | Summary text shown unmodified with a link to the article and its licence. Review questions hide the subject of the first sentence. |
| Quiz items | ${counts.quiz} | Wikidata (elements, countries, capitals, population, area, continents, rivers, mountains, moons, planets) | CC0 1.0 | Templated questions; the answer is computed from the same data. |
| Aptitude items | ${counts.aptitude} | GSM8K, OpenAI (Cobbe et al. 2021) | MIT | Kept only when every calculator step re-computes in code. |
| Riddles | ${counts.riddles} | Written for ORBIT | Original | Curated bank in \`content/riddles\`. |
| Fermi estimates | 65 + generated | Written for ORBIT from standard reference figures | Original | \`src/games/fermiData.ts\` |

## Not used

- AQuA-RAT and MathQA (Apache-2.0): left out of v1. AQuA's answer keys are noisy and its rationales cannot be re-computed reliably in code. MathQA's formula programs could be, which makes it the next aptitude source to add.
- WMO Cloud Atlas (no derivatives), BRAINTEASER (research-only), RiddleSense (no licence), SciQ and current OpenStax (NC), Knights and Knaves datasets (NC-SA): never used. Knights and Knaves puzzles are generated in code.
- No Wikipedia images are shipped. Card illustrations are drawn procedurally.

## Optional enrichment

\`pipeline/enrich.mjs\` can rewrite cards into hook → explanation → why it matters with a local model through Ollama. Each sentence must quote a supporting sentence that exists in the source text, or the card keeps its raw extract. Enriched cards are marked \`modified: true, reviewed: false\` until a human spot-checks them.
`,
  )
}

main().catch((e) => {
  console.error(e)
  process.exit(1)
})
